use std::fmt::Write as _;

use super::decide::{date, Analysis, Kind};
use super::fixups::{kind_title, stamp};
use super::problems::{Problem, ProblemKind};
use super::Input;

const KINDS: [Kind; 5] = [
    Kind::Copies,
    Kind::Versions,
    Kind::Numbers,
    Kind::Moves,
    Kind::Backward,
];

pub fn render(a: &Analysis, input: &Input, problems: &[Problem], command: &str) -> String {
    let mut o = format!("# Snapshot status (generated by `{command}`)\n\n");
    let manual = a.files.values().filter(|f| !f.age.built).count();
    let _ = writeln!(
        o,
        "- {} descriptors (.pb files); {manual} of them listed by no source.",
        a.files.len()
    );
    let mut sources: Vec<_> = input.sources.iter().collect();
    sources.sort_by(|x, y| {
        x.build_time
            .cmp(&y.build_time)
            .then(x.identity.cmp(&y.identity))
    });
    let _ = writeln!(o, "- {} sources:\n", sources.len());
    o.push_str(
        "| Built | Order hint | Group | Identity | Metadata | Files |\n\
         |---|---|---|---|---|---|\n",
    );
    for s in sources {
        let meta: Vec<String> = s
            .metadata
            .iter()
            .filter(|(_, v)| !v.is_empty())
            .map(|(k, v)| format!("{k}={v}"))
            .collect();
        let _ = writeln!(
            o,
            "| {} | {} | `{}` | `{}` | {} | {} |",
            date(s.build_time),
            s.order_hint.map(|h| h.to_string()).unwrap_or_default(),
            s.group.as_deref().unwrap_or(""),
            s.identity,
            meta.join(", "),
            s.paths.len()
        );
    }

    o.push_str("\n## Conflicts and decisions\n\n| Kind | Entries |\n|---|---|\n");
    for k in KINDS {
        let n = a.decisions.iter().filter(|d| d.kind == k).count();
        let _ = writeln!(o, "| {} | {n} |", kind_title(k));
    }
    let _ = writeln!(
        o,
        "\n{} entries in fixups.yaml; {} unresolved ties.",
        a.decisions.len(),
        a.ties.len()
    );
    for k in KINDS {
        let mut ds: Vec<_> = a.decisions.iter().filter(|d| d.kind == k).collect();
        if ds.is_empty() {
            continue;
        }
        ds.sort_by_key(|d| d.directive.render());
        let _ = writeln!(o, "\n### {}\n", kind_title(k));
        for d in ds {
            let _ = writeln!(o, "- `{}`: {}", d.directive.render(), d.comment);
        }
    }

    o.push_str("\n## Problems\n\n");
    if problems.is_empty() {
        o.push_str("None.\n");
    }
    let kinds = [
        ProblemKind::StaleImporter,
        ProblemKind::Refused,
        ProblemKind::MissingImport,
        ProblemKind::Manual,
        ProblemKind::Tie,
        ProblemKind::OutOfOrder,
        ProblemKind::Build,
        ProblemKind::StaleEntry,
    ];
    for k in kinds {
        let ps: Vec<_> = problems.iter().filter(|p| p.kind == k).collect();
        if ps.is_empty() {
            continue;
        }
        let _ = writeln!(o, "### {} ({})\n", k.name(), ps.len());
        for p in ps {
            if k == ProblemKind::Manual {
                let _ = writeln!(o, "- {}: {}", p.detail, p.files.join(", "));
            } else {
                let _ = writeln!(o, "- `{}`: {}", p.files.join("`, `"), p.detail);
            }
            for note in &p.build {
                let _ = writeln!(o, "  - build: {note}");
            }
        }
        o.push('\n');
    }

    o.push_str("## Extraction order\n\n");
    if problems.iter().any(|p| p.kind == ProblemKind::OutOfOrder) {
        o.push_str("Extractions applied after a newer source sharing files with them: see `out-of-order` above.\n");
    } else {
        o.push_str("Every source was applied in build order.\n");
    }

    o.push_str("\n## Computed from\n\n```\n");
    o.push_str(&stamp(&input.sources));
    o.push_str("```\n");
    o
}
